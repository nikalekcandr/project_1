GAME_BY_ID = {g.id: g for g in GAMES}


def games_in_domain(domain: str) -> list[GameMeta]:
    return [g for g in GAMES if g.domain == domain]


def option_values(meta: GameMeta, stored: dict | None) -> dict[str, str]:
    stored = stored or {}
    out = {}
    for opt in meta.options:
        valid = {v for v, _ in opt.choices}
        val = stored.get(opt.key, opt.default)
        out[opt.key] = val if val in valid else opt.default
    return out
